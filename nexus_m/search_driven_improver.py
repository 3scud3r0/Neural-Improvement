"""MCTS AST synthesis with automatic tested promotion and configurable targets.

The 24-program grammar and correctness gate define this search algorithm.
They are not a general plugin permission boundary.
"""
from __future__ import annotations
from dataclasses import dataclass,asdict
from pathlib import Path
import hashlib,heapq,json,os,statistics,time
from .ast_program_synthesis import RouterSpec,compile_source,validate_generated_source,reference_route
from .ast_mcts import ASTSynthesisMCTS
from .ast_candidate_runtime import evaluate
from .ast_formal_gate import verify,promotion_eligible
from .alignment_and_value_core import AlignmentGuard

@dataclass
class PromotionReport:
    selected:dict
    search_simulations:int
    explored_programs:int
    search_elapsed_s:float
    measured_train_gain:float
    heldout_gain:float
    heldout_equivalent:bool
    finite_cases:int
    structurally_terminating:bool
    universal_formal_proof:bool
    staged_source:str
    active_source:str
    active_before_sha256:str
    candidate_sha256:str
    promoted:bool
    reason:str
    audit_ledger_verified:bool
    def as_dict(self):return asdict(self)


def _digest(source:str)->str:return hashlib.sha256(source.encode('utf-8')).hexdigest()

class SearchDrivenImprover:
    def __init__(self,guard:AlignmentGuard,min_gain:float=.05,*,target_path:str="managed/ast_router.py"):
        self.guard=guard
        if not 0<=min_gain<1:raise ValueError('gain must be in 0..1')
        self.min_gain=min_gain
        self.folder=guard.workspace/'managed'
        self.folder.mkdir(parents=True,exist_ok=True)
        self.active=(guard.workspace/target_path).resolve()
        self.active.relative_to(guard.workspace)
        self.active.parent.mkdir(parents=True,exist_ok=True)
        if not self.active.exists():self.active.write_text(compile_source(RouterSpec()),encoding='utf-8')
        self.staged=self.folder/'candidate_ast_router.py'
        self._route=self._load(self.active.read_text(encoding='utf-8'))

    @staticmethod
    def _load(source:str):
        # Executed code MUST match one of the 24 canonical ASTs generated by
        # the in-house compiler. This is not a general arbitrary-code loader.
        validate_generated_source(source)
        builtins={'len':len,'range':range,'sorted':sorted,'min':min,
                  'list':list,'ValueError':ValueError}
        context={'__builtins__':builtins,'heapq':heapq}
        exec(compile(source,'<reviewed_generated_ast>','exec'),context)
        return context['route']

    def route(self,scores,k):return self._route(scores,k)

    def run(self,*,approve:bool|None=None,simulations:int=96,seed:int=2026,
            min_gain:float|None=None)->PromotionReport:
        approve=self.guard.policy.auto_promote_source_changes if approve is None else approve
        if not self.guard.authorize('mcts',{'simulations':simulations,'depth':3}).allowed:
            raise ValueError('search exceeds explicit policy budget')
        if min_gain is not None and not 0<=min_gain<1:raise ValueError('bad threshold')
        threshold=self.min_gain if min_gain is None else min_gain
        previous=self.active.read_text(encoding='utf-8')
        baseline_spec=validate_generated_source(previous)
        search=ASTSynthesisMCTS(simulations=simulations,seed=seed,
                                 baseline_spec=baseline_spec).search()
        candidate_spec=RouterSpec(**search.best_spec)
        source=search.best_source
        self.staged.write_text(source,encoding='utf-8')
        proof=verify(candidate_spec,max_n=5)
        heldout=evaluate(candidate_spec,seed=seed+999_991,large=True,
                         checks=180,timing=65,repetitions=5,timeout=14.,
                         baseline_spec=baseline_spec)
        reason='';promoted=False
        if not promotion_eligible(proof):
            reason='candidate did not pass finite-domain and structural gate'
        elif not heldout.equivalent:
            reason='held-out differential test failed'
        elif heldout.improvement<threshold:
            reason=f'held-out gain {heldout.improvement:.3f} < required {threshold:.3f}'
        elif not approve:
            reason='staged for inspection; human approval required for persistent change'
        elif not self.guard.authorize('source_edit',{'relative_path':str(self.active.relative_to(self.guard.workspace))},approved=True).allowed:
            reason='policy rejected source modification'
        elif not self.guard.authorize('hot_swap',{'relative_path':str(self.active.relative_to(self.guard.workspace))},approved=True).allowed:
            reason='policy rejected hot swap'
        else:
            backup=self.active.with_suffix('.previous.py')
            backup.write_text(previous,encoding='utf-8')
            replacement=self.active.with_suffix('.next.py')
            replacement.write_text(source,encoding='utf-8')
            try:
                new_fn=self._load(source)
                # Additional independent smoke cases before mutating live object.
                for vals in ([1.,1.,2.],[-10.,0.,10.],[],[0.],list(range(120))):
                    for k in (0,min(1,len(vals)),len(vals)):
                        if new_fn(vals,k)!=reference_route(vals,k):
                            raise AssertionError('hot swap smoke equivalence failed')
                os.replace(replacement,self.active)
                self._route=self._load(self.active.read_text(encoding='utf-8'))
                promoted=True
                reason='approved promotion applied atomically; previous source backed up'
            except Exception:
                self.active.write_text(previous,encoding='utf-8')
                self._route=self._load(previous)
                raise
            finally: replacement.unlink(missing_ok=True)
        report=PromotionReport(candidate_spec.as_dict(),simulations,
               search.unique_candidates,search.elapsed_seconds,search.best_train_gain,
               heldout.improvement,heldout.equivalent,proof.checked_cases,
               proof.bounded_loops,proof.machine_checked_universal_proof,
               str(self.staged),str(self.active),_digest(previous),_digest(source),promoted,reason,
               self.guard.verify_ledger())
        reports=self.folder/'autosynth_reports.jsonl'
        with reports.open('a',encoding='utf-8') as f:
            f.write(json.dumps(report.as_dict(),ensure_ascii=False,sort_keys=True)+'\n')
        (self.folder/'ast_search_trace.json').write_text(
            json.dumps(search.as_dict(),indent=2,ensure_ascii=False),encoding='utf-8')
        (self.folder/'proof_evidence.json').write_text(
            json.dumps(proof.as_dict(),indent=2,ensure_ascii=False),encoding='utf-8')
        (self.folder/'heldout_measurement.json').write_text(
            json.dumps(heldout.as_dict(),indent=2,ensure_ascii=False),encoding='utf-8')
        return report

    def rollback(self,*,approve:bool|None=None)->bool:
        backup=self.active.with_suffix('.previous.py')
        if not backup.exists():return False
        approve=self.guard.policy.auto_promote_source_changes if approve is None else approve
        if not approve:raise PermissionError('rollback disabled by caller or policy')
        if not self.guard.authorize('hot_swap',{'relative_path':str(self.active.relative_to(self.guard.workspace))},approved=True).allowed:
            raise PermissionError('rollback denied by policy')
        recovered=backup.read_text(encoding='utf-8')
        fn=self._load(recovered)
        temp=self.active.with_suffix('.rollback.py')
        temp.write_text(recovered,encoding='utf-8')
        os.replace(temp,self.active)
        self._route=fn
        return True
